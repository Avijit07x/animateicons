const cache = new Map<string, ComponentType<any>>();

function getIcon(name: string): ComponentType<any> {
 let comp = cache.get(name);
 if (!comp) {
  const loader = iconLoaders[name];
  comp = lazy(() => loader().then((C) => ({ default: C })));
  cache.set(name, comp);
 }
 return comp;
}

